/* --------------------------------------------------------------- shared --- */

function AnalysisHeader({
  kind,
  version,
  history,
  onRegenerate,
  regenerating,
  onOpenHistory,
}: {
  kind: 'advice' | 'risk'
  version: { modelVersion: string; confidence?: number; createdAt: string; origin: 'auto' | 'manual'; createdByName: string }
  history: Array<{ id: string; createdAt: string }>
  onRegenerate: () => void
  regenerating: boolean
  onOpenHistory: () => void
}) {
  return (
    <div className="flex flex-wrap items-center justify-between gap-3">
      <div className="flex flex-wrap items-center gap-x-3 gap-y-1.5">
        <ModelStamp model={version.modelVersion} confidence={version.confidence} />
        <span className="text-xs text-ink-3" aria-hidden>
          ·
        </span>
        <Recency at={version.createdAt} />
        <span className="text-xs text-ink-3">
          {version.origin === 'manual' ? `regenerated by ${version.createdByName}` : 'recalculated automatically'}
        </span>
      </div>
      <div className="flex items-center gap-2">
        <Button size="sm" variant="outline" icon={<History />} onClick={onOpenHistory}>
          History ({history.length})
        </Button>
        <Button size="sm" variant="primary" icon={<RefreshCw />} loading={regenerating} onClick={onRegenerate}>
          Regenerate {kind}
        </Button>
      </div>
    </div>
  )
}

function HistoryDialog({
  open,
  onOpenChange,
  title,
  versions,
}: {
  open: boolean
  onOpenChange: (open: boolean) => void
  title: string
  versions: Array<{ id: string; createdAt: string; origin: 'auto' | 'manual'; createdByName: string; drivers: Array<{ label: string; before: string; after: string }> }>
}) {
  return (
    <Dialog open={open} onOpenChange={onOpenChange} title={title} description="Every recalculation is kept, with the operations that triggered it.">
      <ol className="space-y-3">
        {versions.map((version, index) => (
          <li key={version.id} className="border-t border-line pt-3 first:border-0 first:pt-0">
            <div className="flex flex-wrap items-center gap-2">
              <Stamp tone={index === 0 ? 'green' : 'neutral'}>{index === 0 ? 'current' : `v${versions.length - index}`}</Stamp>
              <span className="text-sm font-medium text-ink">{formatDateTime(version.createdAt)}</span>
              <span className="text-xs text-ink-3">
                {version.origin === 'manual' ? 'regenerated' : 'automatic'} · {version.createdByName}
              </span>
            </div>
            {version.drivers.length > 0 && (
              <div className="mt-2">
                <UpdatedBecause drivers={version.drivers} compact />
              </div>
            )}
          </li>
        ))}
      </ol>
    </Dialog>
  )
}

/* --------------------------------------------------------------- advice --- */

export function AdviceTab() {
  const bundle = useFarm((s) => s.bundle)
  const recalc = useFarm((s) => s.recalc)
  const regenerate = useFarm((s) => s.regenerate)
  const mode = useUi((s) => s.mode)
  const [historyOpen, setHistoryOpen] = useState(false)
  const [openSections, setOpenSections] = useState<Record<string, boolean>>({})
  const { copied, copy } = useCopyToClipboard()

  const { bundle: b, sections } = useMemo(() => ({ bundle, sections: bundle?.adviceHistory ?? [] }), [bundle])

  if (!bundle) return null
  const advice = b?.analysis.advice
  if (!advice) {
    return (
      <Panel>
        <EmptyState
          title="No advice generated yet"
          description="Advice is produced from the plant record. Add a plant, or regenerate to run the engine over the current properties."
          actions={
            <Button variant="primary" icon={<RefreshCw />} onClick={() => void regenerate(bundle.farm.id)}>
              Generate advice
            </Button>
          }
        />
      </Panel>
    )
  }

  const sectionText = (section: AdviceSection) =>
    section.blocks
      .map((block) => {
        if (block.kind === 'p') return block.text
        if (block.kind === 'why') return `${block.label}: ${block.text}`
        if (block.kind === 'list') return block.items.map((i) => `- ${i}`).join('\n')
        return `${block.caption}\n${block.rows.map((r) => `- ${r.label}: ${r.detail} (${r.when})`).join('\n')}`
      })
      .join('\n\n')

  return (
    <div className="space-y-5">
      <UpdatedBecause drivers={recalc.finishedAt ? advice.drivers : []} />
      {mode === 'farmer' && <HumanJudgmentNote />}
      <AnalysisHeader
        kind="advice"
        version={advice}
        history={sections}
        regenerating={recalc.active && recalc.origin === 'manual'}
        onRegenerate={() => {
          void regenerate(bundle.farm.id).then(() => toast({ tone: 'success', title: 'Advice regenerated', body: `Model ${advice.modelVersion} ran over ${bundle.plants.length} plants.` }))
        }}
        onOpenHistory={() => setHistoryOpen(true)}
      />

      <div className="grid gap-5 lg:grid-cols-[minmax(0,220px)_minmax(0,1fr)]">
        {/* Section index, like the contents page of a field notebook. */}
        <nav aria-label="Advice sections" className="lg:sticky lg:top-[76px] lg:self-start">
          <p className="eyebrow mb-2 px-1">Sections</p>
          <ol className="space-y-0.5">
            {advice.sections.map((section, index) => (
              <li key={section.id}>
                <a
                  href={`#advice-${section.id}`}
                  className="flex items-baseline gap-2.5 rounded-sm px-1.5 py-1.5 text-sm text-ink-2 hover:bg-paper-sunken hover:text-ink"
                >
                  <span className="tnum font-mono text-[11px] text-soil-300">{`${index + 1}`.padStart(2, '0')}</span>
                  <span className="min-w-0 flex-1">
                    <span className="block font-medium">{section.title}</span>
                    <span className="mt-0.5 block text-xs leading-snug text-ink-3">{section.gist}</span>
                  </span>
                </a>
              </li>
            ))}
          </ol>
          <Divider className="my-3" />
          <p className="px-1 text-xs leading-relaxed text-ink-3">
            Advice is decision support from the property record, not a guarantee. Agronomic judgement still applies — the
            engine shows its drivers so you can disagree with it.
          </p>
        </nav>

        <div className="space-y-5">
          {advice.sections.map((section, index) => {
            const expanded = openSections[section.id] ?? index < 2
            return (
              <Panel key={section.id} id={`advice-${section.id}`} className="scroll-mt-24">
                <PanelHead
                  title={
                    <span className="flex items-baseline gap-2.5">
                      <span className="tnum font-mono text-[11px] font-normal text-soil-300">{`${index + 1}`.padStart(2, '0')}</span>
                      {section.title}
                    </span>
                  }
                  meta={section.gist}
                  actions={
                    <>
                      <Tip content={copied === section.id ? 'Copied' : 'Copy this section as text'}>
                        <Button
                          size="sm"
                          variant="quiet"
                          icon={copied === section.id ? <Check /> : <Copy />}
                          aria-label={`Copy ${section.title} as text`}
                          onClick={() => {
                            copy(sectionText(section), section.id)
                            toast({ tone: 'info', title: 'Section copied', body: section.title })
                          }}
                        />
                      </Tip>
                      <Button size="sm" variant="quiet" onClick={() => setOpenSections((open) => ({ ...open, [section.id]: !expanded }))}>
                        {expanded ? 'Collapse' : 'Expand'}
                      </Button>
                    </>
                  }
                />
                {expanded && (
                  <PanelBody className="space-y-4 fade-up">
                    <AdviceBlocks blocks={section.blocks} />
                    <Drivers title="Drivers for this section" items={section.drivers} />
                  </PanelBody>
                )}
              </Panel>
            )
          })}
        </div>
      </div>

      <HistoryDialog open={historyOpen} onOpenChange={setHistoryOpen} title="Advice version history" versions={sections} />
    </div>
  )
}

/* ----------------------------------------------------------------- risk --- */

const CATEGORY_ORDER: RiskCategory[] = ['drought', 'flood', 'pest-disease', 'nutrient', 'market']

export function RiskTab() {
  const bundle = useFarm((s) => s.bundle)
  const recalc = useFarm((s) => s.recalc)
  const regenerate = useFarm((s) => s.regenerate)
  const [historyOpen, setHistoryOpen] = useState(false)
  const [filter, setFilter] = useState<RiskCategory | 'all'>('all')
  const [expanded, setExpanded] = useState<string | null>(null)

  if (!bundle) return null
  const risk = bundle.analysis.risk
  const history = bundle.riskHistory

  if (!risk || !risk.items.length) {
    return (
      <Panel>
        <EmptyState
          title="No risks above the reporting threshold"
          description="Every scored category — drought, flood, pest and disease, nutrient balance and market exposure — is currently below the level worth acting on."
          actions={
            <Button variant="outline" icon={<RefreshCw />} onClick={() => void regenerate(bundle.farm.id)}>
              Re-score now
            </Button>
          }
        />
      </Panel>
    )
  }

  const counts = risk.items.reduce<Record<string, number>>((acc, item) => {
    acc[item.category] = (acc[item.category] ?? 0) + 1
    return acc
  }, {})

  const visible = filter === 'all' ? risk.items : risk.items.filter((item) => item.category === filter)

  return (
    <div className="space-y-5">
      <UpdatedBecause drivers={recalc.finishedAt ? risk.drivers : []} />

      <div className="flex flex-wrap items-start justify-between gap-4">
        <SectionHead
          eyebrow={`Overall exposure · ${SEVERITY_LABELS[risk.overall]}`}
          title="Risk register"
          description="Each item carries a likelihood, the drivers behind it, and what to do about it. Severity is always written out as well as coloured."
        />
        <div className="flex items-center gap-2">
          <Button size="sm" variant="outline" icon={<History />} onClick={() => setHistoryOpen(true)}>
            History ({history.length})
          </Button>
          <Button
            size="sm"
            variant="primary"
            icon={<RefreshCw />}
            loading={recalc.active && recalc.origin === 'manual'}
            onClick={() => void regenerate(bundle.farm.id)}
          >
            Re-score risks
          </Button>
        </div>
      </div>

      {/* Severity ladder — the count per band, as a ledger line. */}
      <dl className="grid grid-cols-2 gap-y-4 border-y border-line-strong py-3.5 sm:grid-cols-4">
        {(['low', 'moderate', 'high', 'critical'] as Severity[]).map((band) => {
          const count = risk.items.filter((i) => i.severity === band).length
          return (
            <div key={band} className="border-l border-line pl-3.5 first:border-l-0 first:pl-0">
              <dt className="eyebrow">{SEVERITY_LABELS[band]}</dt>
              <dd className={cn('tnum mt-1 font-display text-2xl leading-none', count ? 'text-ink' : 'text-soil-300')}>{count}</dd>
            </div>
          )
        })}
      </dl>

      <div className="flex flex-wrap items-center gap-2">
        <Segmented
          label="Filter risks by category"
          value={filter}
          onChange={(value) => setFilter(value)}
          size="md"
          options={[
            { value: 'all', label: `All (${risk.items.length})` },
            ...CATEGORY_ORDER.filter((c) => counts[c]).map((c) => ({
              value: c,
              label: `${c.replace('-', ' & ')} (${counts[c]})`,
            })),
          ]}
        />
      </div>

      <div className="space-y-4">
        {visible.map((item) => (
          <RiskCard key={item.id} item={item} open={expanded === item.id} onToggle={() => setExpanded(expanded === item.id ? null : item.id)} />
        ))}
        {!visible.length && (
          <InlineAlert tone="info">Nothing in this category is currently above the reporting threshold.</InlineAlert>
        )}
      </div>

      <HistoryDialog open={historyOpen} onOpenChange={setHistoryOpen} title="Risk version history" versions={history} />
    </div>
  )
}

function RiskCard({ item, open, onToggle }: { item: RiskItem; open: boolean; onToggle: () => void }) {
  const accent = item.severity === 'critical' ? 'clay' : item.severity === 'high' ? 'clay' : item.severity === 'moderate' ? 'marigold' : 'green'
  return (
    <Panel accent={accent}>
      <div className="grid gap-0 lg:grid-cols-[minmax(0,1fr)_minmax(0,260px)]">
        <div className="p-4 sm:p-5">
          <div className="flex flex-wrap items-center gap-2">
            <Stamp tone="plain" className="border-line-strong text-ink-2">
              {item.categoryLabel}
            </Stamp>
            <SeverityStamp severity={item.severity} />
            <span className="text-xs text-ink-3">{item.window}</span>
          </div>
          <h3 className="mt-2.5 font-display text-lg leading-snug text-ink">{item.title}</h3>
          <p className="mt-1.5 max-w-[70ch] text-sm leading-relaxed text-ink-2">{item.impact}</p>

          {open && (
            <div className="mt-4 space-y-4 fade-up">
              <AdviceBlocks blocks={item.blocks} />
              <Drivers title="What drove this" items={item.drivers} />
            </div>
          )}

          <div className="mt-3.5 flex items-center gap-2">
            <Button size="sm" variant="quiet" icon={<TriangleAlert />} onClick={onToggle}>
              {open ? 'Hide the reasoning' : 'Show the reasoning'}
            </Button>
          </div>
        </div>

        <aside className="border-t border-line bg-paper-sunken/50 p-4 lg:border-l lg:border-t-0">
          <div className="lg:sticky lg:top-[80px]">
            <Meter
              label="Modelled likelihood"
              valueLabel={`${Math.round(item.likelihood * 100)} %`}
              value={item.likelihood * 100}
              tone={item.severity === 'high' || item.severity === 'critical' ? 'danger' : item.severity === 'moderate' ? 'warn' : 'green'}
            />
            <p className="eyebrow mt-4">What to do</p>
            <ul className="mt-2 space-y-1.5">
              {item.mitigation.map((step) => (
                <li key={step} className="flex gap-2 text-sm text-ink-2">
                  <Check size={13} className="mt-[5px] flex-none text-green-600" aria-hidden />
                  {step}
                </li>
              ))}
            </ul>
          </div>
        </aside>
      </div>
    </Panel>
  )
}

/** Severity ladder, written out so the bands are never implied by colour alone. */
export function SeverityLegend() {
  return (
    <p className="text-xs text-ink-3">
      Bands: Low below 26 % modelled likelihood, Moderate 26–50 %, High 50–75 %, Critical above 75 %.
    </p>
  )
}
